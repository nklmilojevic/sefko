func TestIfTrusted(t *testing.T) {
	e := setup(t, true)

	// No project at all: the command runs unchanged and quietly.
	t.Chdir(t.TempDir())
	code, _, errOut := e.run("exec", "--if-trusted", "--", "true")
	if code != 0 || errOut != "" || e.exec.path == "" {
		t.Fatalf("no project: %d %q", code, errOut)
	}

	// Not trusted: unchanged, with a note, and nothing read from 1Password.
	path := schemaRepo(t)
	root := filepath.Dir(path)
	t.Chdir(root)
	e.exec.path = ""
	code, _, errOut = e.run("exec", "--if-trusted", "--", "true")
	if code != 0 || !strings.Contains(errOut, "sefko trust") || e.exec.path == "" {
		t.Fatalf("untrusted: %d %q", code, errOut)
	}
	if lookup(e.exec.env, "APP_KEY") != "" || len(e.op.Calls()) != 0 {
		t.Fatal("untrusted project served secrets")
	}

	if code, _, errOut := e.run("trust"); code != 0 {
		t.Fatalf("trust: %d %q", code, errOut)
	}
	code, _, errOut = e.run("exec", "--if-trusted", "--", "true")
	if code != 0 {
		t.Fatalf("trusted: %d %q", code, errOut)
	}
	if v := lookup(e.exec.env, "API_TOKEN"); v != "value-of:op://Dev/Api/credential" {
		t.Fatalf("API_TOKEN=%q", v)
	}

	if code, _, _ := e.run("exec", "--if-trusted", "--project", "--", "true"); code != ExitUsage {
		t.Fatalf("both flags: %d", code)
	}
	// A named alias could stop the command, which --if-trusted never does.
	for _, args := range [][]string{{"github"}, {"--env", "X=github"}, {"missing"}} {
		argv := append(append([]string{"exec", "--if-trusted"}, args...), "--", "true")
		if code, _, _ := e.run(argv...); code != ExitUsage {
			t.Fatalf("%v: %d", args, code)
		}
	}
}

// varlock loads the schema of the working directory, or the one that
// package.json names, and never one of a parent directory. A secret of
// another schema would reach the command through the environment.
func TestIfTrustedUsesTheSchemaVarlockLoads(t *testing.T) {
	e := setup(t, true)
	path := schemaRepo(t)
	root := filepath.Dir(path)
	t.Chdir(root)
	if code, _, errOut := e.run("trust"); code != 0 {
		t.Fatalf("trust: %d %q", code, errOut)
	}

	sub := filepath.Join(root, "app")
	t.Chdir(sub)
	code, _, errOut := e.run("exec", "--if-trusted", "--", "true")
	if code != 0 || errOut != "" || e.exec.path == "" || lookup(e.exec.env, "APP_KEY") != "" {
		t.Fatalf("subdirectory: %d %q", code, errOut)
	}
	write(t, filepath.Join(sub, "package.json"), `{"varlock": {"loadPath": "../"}}`)
	if code, _, errOut := e.run("exec", "--if-trusted", "--", "true"); code != 0 || lookup(e.exec.env, "APP_KEY") == "" {
		t.Fatalf("loadPath to the schema: %d %q", code, errOut)
	}

	t.Chdir(root)
	write(t, filepath.Join(root, "package.json"), `{"varlock": {"loadPath": "./app/"}}`)
	code, _, errOut = e.run("exec", "--if-trusted", "--", "true")
	if code != 0 || errOut != "" || lookup(e.exec.env, "APP_KEY") != "" {
		t.Fatalf("loadPath elsewhere: %d %q", code, errOut)
	}
}

