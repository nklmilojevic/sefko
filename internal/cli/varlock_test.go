const schema = `# @plugin(@varlock/1password-plugin)
# @initOp(allowAppAuth=true, account=team.example)
# ---
APP_NAME=acme
# @sensitive
APP_KEY=op("op://Employee/App/key")
DB_PASSWORD=op("op://Dev/Database/password")
API_TOKEN=op("op://Dev/Api/credential")
BRANCH_ONLY=if($BRANCH, op("op://Dev/Branch/credential"))
`

// schemaRepo writes a varlock schema at the root of a repository called
// acme and moves into a subdirectory of it.
func schemaRepo(t *testing.T) string {
	t.Helper()
	root := filepath.Join(t.TempDir(), "acme")
	for _, d := range []string{".git", filepath.Join("app", "src")} {
		if err := os.MkdirAll(filepath.Join(root, d), 0o700); err != nil {
			t.Fatal(err)
		}
	}
	path := filepath.Join(root, config.SchemaFile)
	if err := os.WriteFile(path, []byte(schema), 0o600); err != nil {
		t.Fatal(err)
	}
	t.Chdir(filepath.Join(root, "app", "src"))
	return path
}

func write(t *testing.T, path, data string) {
	t.Helper()
	if err := os.WriteFile(path, []byte(data), 0o600); err != nil {
		t.Fatal(err)
	}
}

func TestTrustSchema(t *testing.T) {
	e := setup(t, true)
	path := schemaRepo(t)
	name := config.SchemaProjectName(path)
	if !strings.HasPrefix(name, "acme-") {
		t.Fatalf("project name %q", name)
	}

	code, out, errOut := e.run("trust")
	if code != 0 {
		t.Fatalf("trust: %d %q", code, errOut)
	}
	for _, want := range []string{"trusted " + name + " from " + path, name + "/app_key", "APP_KEY", "op://Dev/Database/password", "left to varlock", "BRANCH_ONLY"} {
		if !strings.Contains(out, want) {
			t.Fatalf("trust output lacks %q:\n%s", want, out)
		}
	}
	trusted, err := os.ReadFile(config.TrustedPath(e.cfg, name))
	if err != nil || !strings.HasPrefix(string(trusted), "# Generated by `sefko trust`") {
		t.Fatalf("trusted copy: %v\n%s", err, trusted)
	}
	if calls := e.op.Calls(); len(calls) != 0 {
		t.Fatalf("trust fetched secrets: %q", calls)
	}

	code, _, errOut = e.run("exec", "--project", "--", "true")
	if code != 0 {
		t.Fatalf("exec: %d %q", code, errOut)
	}
	if v := lookup(e.exec.env, "APP_KEY"); v != "value-of:op://Employee/App/key" {
		t.Fatalf("APP_KEY=%q", v)
	}
	if code, out, _ := e.run("get", name+"/db_password"); code != 0 || out != "value-of:op://Dev/Database/password" {
		t.Fatalf("get: %d %q", code, out)
	}

	// A change that does not touch an op() item keeps the trust.
	write(t, path, strings.Replace(schema, "APP_NAME=acme", "APP_NAME=renamed\nNEW_FLAG=1", 1))
	if code, _, errOut := e.run("trust", "--check"); code != 0 {
		t.Fatalf("check after unrelated change: %d %q", code, errOut)
	}
	// A changed reference needs a new trust.
	write(t, path, strings.Replace(schema, "op://Dev/Api/credential", "op://Private/Else/credential", 1))
	code, _, errOut = e.run("exec", "--project", "--", "true")
	if code != ExitNotAllowed || !strings.Contains(errOut, "changed since you trusted it") {
		t.Fatalf("changed exec: %d %q", code, errOut)
	}
	if code, _, _ := e.run("untrust"); code != 0 {
		t.Fatalf("untrust: %d", code)
	}
	if code, _, _ := e.run("get", name+"/app_key"); code != ExitNotAllowed {
		t.Fatalf("get after untrust: %d", code)
	}
}

func TestSchemaKeepsLocalOverrides(t *testing.T) {
	e := setup(t, true)
	path := schemaRepo(t)
	if code, _, errOut := e.run("trust"); code != 0 {
		t.Fatalf("trust: %d %q", code, errOut)
	}
	write(t, filepath.Join(filepath.Dir(path), ".env"), "DB_PASSWORD=my-own\n")
	t.Setenv("API_TOKEN", "from-the-shell")

	code, _, errOut := e.run("exec", "--project", "--", "true")
	if code != 0 {
		t.Fatalf("exec: %d %q", code, errOut)
	}
	if v := lookup(e.exec.env, "APP_KEY"); v != "value-of:op://Employee/App/key" {
		t.Fatalf("APP_KEY=%q", v)
	}
	if v := lookup(e.exec.env, "DB_PASSWORD"); v != "" {
		t.Fatalf("DB_PASSWORD from .env was replaced with %q", v)
	}
	if v := lookup(e.exec.env, "API_TOKEN"); v != "from-the-shell" {
		t.Fatalf("API_TOKEN=%q", v)
	}
	for _, c := range e.op.Calls() {
		if strings.Contains(c, "Database") || strings.Contains(c, "Api") {
			t.Fatalf("fetched an overridden secret: %s", c)
		}
	}

	code, out, _ := e.run("env", "--project", "--shell", "posix")
	if code != 0 || !strings.Contains(out, "export APP_KEY=") || strings.Contains(out, "DB_PASSWORD") || strings.Contains(out, "API_TOKEN") {
		t.Fatalf("env: %d %q", code, out)
	}
}

